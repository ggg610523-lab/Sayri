static UIColor lerp_color(
    UIColor a, UIColor b, float t)
{
    if (t < 0) t = 0;
    if (t > 1) t = 1;
    return (UIColor){
        (Uint8)(a.r + (b.r - a.r) * t),
        (Uint8)(a.g + (b.g - a.g) * t),
        (Uint8)(a.b + (b.b - a.b) * t),
        (Uint8)(a.a + (b.a - a.a) * t)
    };
}

