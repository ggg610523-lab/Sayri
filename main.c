#define CHAT_WRAP_LINES 24
#define CHAT_LINE_CAP 512

/*
    Word-wrap text into lines that fit max_w.
    Honors explicit newlines. Returns line count;
    output is truncated at max_lines with an
    ellipsis.
*/
static int wrap_lines(
    TTF_Font *font,
    const char *text,
    int max_w,
    char out[][CHAT_LINE_CAP],
    int max_lines)
{
    int count = 0;

    out[0][0] = '\0';

    const char *p = text;

    while (*p) {

        /*
            One paragraph per explicit newline.
        */
        const char *nl = strchr(p, '\n');

        size_t seg_len =
            nl ? (size_t)(nl - p)
               : strlen(p);

        char seg[CHAT_LINE_CAP];

        snprintf(seg, sizeof(seg),
                 "%.*s", (int)seg_len, p);

        char *save = NULL;

        for (char *word =
                strtok_r(seg, " ", &save);
             word;
             word = strtok_r(NULL, " ", &save)) {

            char candidate[CHAT_LINE_CAP];
            int cur_len =
                (int)strlen(out[count]);

            snprintf(candidate,
                     sizeof(candidate),
                     "%s%s%s",
                     out[count],
                     cur_len ? " " : "",
                     word);

            int w = 0;
            TTF_SizeUTF8(font, candidate,
                         &w, NULL);

            if (cur_len == 0 || w <= max_w) {
                snprintf(out[count],
                         sizeof(out[count]),
                         "%s", candidate);

            } else {

                if (count + 1 >= max_lines) {
                    size_t len =
                        strlen(out[count]);
                    snprintf(
                        out[count] + len,
                        sizeof(out[count]) - len,
                        "\u2026");
                    return count + 1;
                }

                count++;
                snprintf(out[count],
                         sizeof(out[count]),
                         "%s", word);
            }
        }

        if (!nl)
            break;

        p = nl + 1;

        if (*p && count + 1 < max_lines) {
            count++;
            out[count][0] = '\0';
        } else if (!*p) {
            break;
        }
    }

    return count + 1;
}

static void draw_chat_area(
    SDL_Renderer *renderer,
    AppState *state,
    UIContext *ui,
    TTF_Font *font,
    int x, int y, int w, int h)
{
    SDL_Rect container = {x, y, w, h};

    ui_fill_rounded_rect(
        renderer, container,
        (int)roundf(18.0f * ui->scale),
        ui->dark
        ? (UIColor){26, 26, 29, 190}
        : (UIColor){240, 245, 252, 175});

    SDL_RenderSetClipRect(renderer, &container);

    int pad =
        (int)roundf(14.0f * ui->scale);

    int msgH =
        (int)roundf(38.0f * ui->scale);

    int msgGap =
        (int)roundf(6.0f * ui->scale);

    int curY =
        y + h - pad +
        (int)state->scroll_offset;

    for (int i = state->count - 1; i >= 0; i--) {

        ChatMessage *m = &state->messages[i];
        if (m->alpha < 0.01f) continue;

        int maxBubbleW = w - pad * 2 -
            (int)roundf(40.0f * ui->scale);

        int bubbleW =
            m->is_user
            ? (int)(maxBubbleW * 0.60f)
            : (int)(maxBubbleW * 0.75f);

        if (bubbleW < 60) bubbleW = 60;

        int textPad =
            (int)roundf(12.0f * ui->scale);

        int bubbleX =
            m->is_user
            ? x + w - pad - bubbleW
            : x + pad;

        /*
            Wrap into lines that fit the bubble.
        */
        char lines[CHAT_WRAP_LINES][CHAT_LINE_CAP];

        int lineCount =
            wrap_lines(
                font, m->text,
                bubbleW - textPad * 2,
                lines, CHAT_WRAP_LINES);

        int fontH = TTF_FontHeight(font);

        int lineH = fontH +
            (int)roundf(3.0f * ui->scale);

        int padV =
            (int)roundf(9.0f * ui->scale);

        int bubbleH =
            lineCount * lineH + padV * 2;

        if (bubbleH < msgH)
            bubbleH = msgH;

        curY -= bubbleH + msgGap;
        int bubbleY =
            curY + (int)(m->slide_y * (1.0f - m->alpha));

        Uint8 bgA =
            (Uint8)(180.0f * m->alpha);

        SDL_Rect bubble = {
            bubbleX, bubbleY, bubbleW, bubbleH};

        if (m->is_user) {
            ui_fill_rounded_rect(
                renderer, bubble,
                (int)roundf(14.0f * ui->scale),
                ui->dark
                ? (UIColor){62, 62, 70, bgA}
                : (UIColor){200, 210, 240, bgA});
        } else {
            ui_fill_rounded_rect(
                renderer, bubble,
                (int)roundf(14.0f * ui->scale),
                ui->dark
                ? (UIColor){44, 44, 49, bgA}
                : (UIColor){230, 235, 248, bgA});
        }

        Uint8 tA =
            (Uint8)(230.0f * m->alpha);

        int textY = bubbleY +
            (bubbleH - lineCount * lineH) / 2;

        UIColor textColor =
            m->is_user
            ? ui_theme(ui->dark,
                  (UIColor){35, 45, 80, tA},
                  (UIColor){225, 232, 250, tA})
            : ui_theme(ui->dark,
                  (UIColor){50, 55, 85, tA},
                  (UIColor){208, 216, 236, tA});

        for (int k = 0; k < lineCount; k++) {
            ui_text(
                renderer, font, lines[k],
                bubbleX + textPad,
                textY + k * lineH,
                textColor);
        }
    }

    SDL_RenderSetClipRect(renderer, NULL);
}

static void draw_input_bar(
    SDL_Renderer *renderer,
    AppState *state,
    UIContext *ui,
    TTF_Font *font,
    int x, int y, int w, int h,
    float time)
{
    SDL_Rect bar = {x, y, w, h};

    ui_fill_rounded_rect(
        renderer, bar,
        (int)roundf(14.0f * ui->scale),
        state->input_focused
        ? ui_theme(ui->dark,
              (UIColor){246, 250, 255, 205},
              (UIColor){40, 40, 45, 215})
        : ui_theme(ui->dark,
              (UIColor){240, 245, 252, 175},
              (UIColor){24, 24, 27, 185}));

    int pad =
        (int)roundf(14.0f * ui->scale);

    if (state->input_len > 0) {
        ui_text(
            renderer, font, state->input,
            x + pad,
            y + (h - (int)roundf(
                17.0f * ui->scale)) / 2,
            ui_theme(ui->dark,
                (UIColor){30, 35, 60, 255},
                (UIColor){220, 228, 245, 255}));
    } else {
        ui_text(
            renderer, font,
            "Ask Sayri\u2026",
            x + pad,
            y + (h - (int)roundf(
                17.0f * ui->scale)) / 2,
            ui_theme(ui->dark,
                (UIColor){140, 145, 170, 180},
                (UIColor){125, 133, 158, 180}));
    }

    if (state->input_focused) {
        float blink =
            fmodf(
                (float)SDL_GetTicks() / 1000.0f,
                1.0f);

        if (blink < 0.5f) {
            int textW = 0;
            if (state->input_len > 0)
                TTF_SizeUTF8(
                    font, state->input,
                    &textW, NULL);

            int cx = x + pad + textW + 2;
            int ch = (int)roundf(16.0f * ui->scale);

            float ct = fmodf(time * 2.0f, 4.0f);
            UIColor cc;
            UIColor c1 = {110, 140, 235, 255};
            UIColor c2 = {230, 130, 195, 255};
            UIColor c3 = {170, 140, 220, 255};
            UIColor c4 = {100, 200, 185, 255};

            if (ct < 1.0f)
                cc = lerp_color(c1, c2, ct);
            else if (ct < 2.0f)
                cc = lerp_color(c2, c3, ct - 1.0f);
            else if (ct < 3.0f)
                cc = lerp_color(c3, c4, ct - 2.0f);
            else
                cc = lerp_color(c4, c1, ct - 3.0f);

            cc.a = 230;

            SDL_SetRenderDrawBlendMode(
                renderer, SDL_BLENDMODE_BLEND);
            SDL_SetRenderDrawColor(
                renderer,
                cc.r, cc.g, cc.b, cc.a);
            SDL_RenderDrawLine(
                renderer,
                cx, y + (h - ch) / 2,
                cx, y + (h + ch) / 2);
        }
    }
}

